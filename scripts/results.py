"""Regenerate docs/results/<pack>.md from the heuristic judge and recorded cassettes.

Every number in that file comes from this script, offline:

    uv run python scripts/results.py collections-conduct
"""

from __future__ import annotations

import statistics
import sys
from pathlib import Path

from precedent.engine import decide
from precedent.gate import run_gate
from precedent.judge import Judge, judge_all
from precedent.judge.cassette import ReplayJudge
from precedent.judge.heuristic import HeuristicJudge
from precedent.models import Correction, JudgeOutput
from precedent.pack import Pack, load_pack

ROOT = Path(__file__).resolve().parents[1]


def _rate(pairs: list[tuple[str, str]]) -> str:
    ok = sum(a == b for a, b in pairs)
    return f"{ok}/{len(pairs)} ({ok / len(pairs):.1%})" if pairs else "—"


def _pairs(
    pack: Pack, outputs: dict[str, JudgeOutput], split: str | None = None, item: str | None = None
) -> list[tuple[str, str]]:
    pairs = []
    for case in pack.cases:
        if split and case.split != split:
            continue
        decisions = decide(pack, outputs[case.id], [])
        for it, label in case.golden.items():
            if item is None or it == item:
                pairs.append((decisions[it].label, label))
    return pairs


def _correction(pack: Pack) -> Correction:
    """The demo correction, as recorded against the heuristic judge."""
    case = pack.case("CASE-019")
    return Correction(
        id="C-0001",
        pack=pack.id,
        case_id=case.id,
        case_hash=case.hash,
        item="escalation_offered",
        ai_label="needs_review",
        human_label="pass",
        reviewer="maria",
        error_type="policy_misinterpretation",
    )


def main(pack_name: str) -> int:
    pack = load_pack(pack_name)
    judges: list[Judge] = [HeuristicJudge(pack)]
    jdir = pack.judgements_dir()
    if jdir and jdir.is_dir():
        judges += [ReplayJudge(p) for p in sorted(jdir.glob("*.jsonl"))]

    lines = [
        f"# Results: `{pack.id}`",
        "",
        f"Generated by `scripts/results.py {pack.id}`. {len(pack.cases)} cases, "
        f"{sum(c.split == 'heldout' for c in pack.cases)} held out, one annotator: "
        "a smoke test, not a benchmark.",
        "",
        "## Judge agreement with the labels (no rules)",
        "",
        "| judge | all verdicts | held-out | " + " | ".join(i.id for i in pack.items) + " |",
        "|---|---|---|" + "---|" * len(pack.items),
    ]
    all_outputs: dict[str, dict[str, JudgeOutput]] = {}
    for judge in judges:
        outputs = judge_all(judge, pack.cases)
        all_outputs[judge.judge_id] = outputs
        per_item = " | ".join(_rate(_pairs(pack, outputs, item=i.id)) for i in pack.items)
        lines.append(
            f"| `{judge.judge_id}` | {_rate(_pairs(pack, outputs))} | "
            f"{_rate(_pairs(pack, outputs, split='heldout'))} | {per_item} |"
        )

    cost_rows = []
    for jid, outputs in all_outputs.items():
        lat = [o.meta["latency_ms"] for o in outputs.values() if "latency_ms" in o.meta]
        tok = [
            o.meta["usage"]["total_tokens"]
            for o in outputs.values()
            if o.meta.get("usage", {}).get("total_tokens")
        ]
        if lat:
            cost_rows.append(
                f"| `{jid}` | {statistics.median(lat) / 1000:.1f} s | "
                f"{max(lat) / 1000:.1f} s | {statistics.median(tok):.0f} |"
            )
    if cost_rows:
        lines += [
            "",
            "## Cost of a recorded run",
            "",
            "| judge | median latency per case | slowest case | median tokens per case |",
            "|---|---|---|---|",
            *cost_rows,
        ]

    lines += ["", "## Disagreements", ""]
    for jid, outputs in all_outputs.items():
        lines.append(f"**`{jid}`**")
        lines.append("")
        found = False
        for case in pack.cases:
            decisions = decide(pack, outputs[case.id], [])
            for it, label in case.golden.items():
                if decisions[it].label != label:
                    found = True
                    got = decisions[it].label
                    lines.append(f"- {case.id} `{it}`: judge `{got}`, label `{label}`")
        if not found:
            lines.append("- none")
        lines.append("")

    lines += [
        "## The demo correction through the gate",
        "",
        "The correction on CASE-019 (`escalation_offered` → `pass`) and the two rules in "
        "`rules/`, gated against each judge's outputs with no other active rules. "
        '"Fixes" and "breaks" are relative to that judge alone: a strong judge leaves '
        "less to fix, and a bad rule still breaks what it got right.",
        "",
        "| judge | rule | decision | fixes | breaks | exact McNemar p | held-out before → after |",
        "|---|---|---|---|---|---|---|",
    ]
    rules = {r.key: r for r in pack.example_rules()}
    corr = _correction(pack)
    for jid, outputs in all_outputs.items():
        for key, rule in rules.items():
            report = run_gate(pack, outputs, [], rule, [corr])
            lab, held = report.labelled, report.heldout
            assert lab is not None
            heldout = f"{held.right_before}/{held.n} → {held.right_after}/{held.n}" if held else "—"
            lines.append(
                f"| `{jid}` | `{key}` | {report.decision} | {lab.fixes} | {lab.breaks} "
                f"| {lab.mcnemar_p:.2f} | {heldout} |"
            )
    lines.append("")

    out = ROOT / "docs" / "results" / f"{pack.id}.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print(out.read_text())
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1] if len(sys.argv) > 1 else "collections-conduct"))
